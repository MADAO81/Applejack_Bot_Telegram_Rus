def fill_db():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    inserted = 0
    for recipe in RECIPES:
        cursor.execute("""
            INSERT INTO recipes (name, category, ingredients, instructions, tip, source)
            VALUES (?, ?, ?, ?, ?, ?)
        """, (
            recipe['name'],
            recipe['category'],
            recipe['ingredients'],
            recipe['instructions'],
            recipe.get('tip', ''),
            'Эпплджек'
        ))
        inserted += 1

    conn.commit()
    conn.close()
    print(f"✅ Добавлено {inserted} рецептов в базу данных: {DB_PATH}")

if __name__ == "__main__":
    fill_db()
